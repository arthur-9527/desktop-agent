# ============================================================================
# 导出函数
# ============================================================================

def get_shortcuts(os_type: str) -> str:
    """根据操作系统类型获取对应的快捷键参考表
    
    Args:
        os_type: 操作系统类型 Windows / macOS / Linux
        
    Returns:
        格式化后的快捷键参考表文本
    """
    shortcuts_map = {
        "Windows": WINDOWS_SHORTCUTS,
        "macOS": MACOS_SHORTCUTS,
        "Linux": LINUX_SHORTCUTS,
    }
    
    # 默认返回 Windows
    return shortcuts_map.get(os_type, WINDOWS_SHORTCUTS)


